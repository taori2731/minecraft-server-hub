export const coManagementMessages: Record<CoManagementLocale, CoManagementMessages> = { en, ja, "zh-CN": zhCN, "zh-TW": zhTW, ko, es, de, fr, "pt-BR": ptBR };

const localeIntlNames: Record<CoManagementLocale, string> = {
  en: "en-US",
  ja: "ja-JP",
  "zh-CN": "zh-CN",
  "zh-TW": "zh-TW",
  ko: "ko-KR",
  es: "es-ES",
  de: "de-DE",
  fr: "fr-FR",
  "pt-BR": "pt-BR",
};

export function intlLocaleForCoManagement(locale: CoManagementLocale): string {
  return localeIntlNames[locale];
}

export function detectCoManagementLocale(languages: readonly string[] = typeof navigator === "undefined" ? ["en"] : navigator.languages): CoManagementLocale {
  for (const raw of languages.length ? languages : [typeof navigator === "undefined" ? "en" : navigator.language]) {
    const normalized = raw.toLowerCase();
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("zh-tw") || normalized.startsWith("zh-hk") || normalized.startsWith("zh-hant")) return "zh-TW";
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("ko")) return "ko";
    if (normalized.startsWith("es")) return "es";
    if (normalized.startsWith("de")) return "de";
    if (normalized.startsWith("fr")) return "fr";
    if (normalized.startsWith("pt")) return "pt-BR";
    if (normalized.startsWith("en")) return "en";
  }
  return "en";
}

export function readCoManagementPreference(): CoManagementLanguagePreference {
  try {
    const saved = window.localStorage.getItem(CO_MANAGEMENT_LOCALE_STORAGE_KEY);
    return coManagementLanguageOptions.some((option) => option.value === saved) ? saved as CoManagementLanguagePreference : "system";
  } catch {
    return "system";
  }
}

interface CoManagementI18nContextValue {
  locale: CoManagementLocale;
  preference: CoManagementLanguagePreference;
  messages: CoManagementMessages;
  setPreference: (preference: CoManagementLanguagePreference) => void;
}

const CoManagementI18nContext = createContext<CoManagementI18nContextValue | undefined>(undefined);

export function CoManagementI18nProvider({ children }: { children: ReactNode }) {
  const [preference, setPreferenceState] = useState<CoManagementLanguagePreference>(() => readCoManagementPreference());
  const locale = preference === "system" ? detectCoManagementLocale() : preference;
  const messages = coManagementMessages[locale];
  const setPreference = useCallback((next: CoManagementLanguagePreference) => {
    setPreferenceState(next);
    try {
      window.localStorage.setItem(CO_MANAGEMENT_LOCALE_STORAGE_KEY, next);
    } catch {
      // A restricted browser can still use the selector for this session.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = messages.pageTitle;
  }, [locale, messages.pageTitle]);

  const value = useMemo(() => ({ locale, preference, messages, setPreference }), [locale, messages, preference, setPreference]);
  return <CoManagementI18nContext.Provider value={value}>{children}</CoManagementI18nContext.Provider>;
}

export function useCoManagementI18n(): CoManagementI18nContextValue {
  const value = useContext(CoManagementI18nContext);
  if (!value) throw new Error("useCoManagementI18n must be used inside CoManagementI18nProvider");
  return value;
}

export function LanguagePicker() {
  const { preference, setPreference, messages } = useCoManagementI18n();
  return <label className="language-control">
    <span>{messages.languagePickerLabel}</span>
    <select data-testid="co-management-language-picker" aria-label={messages.languagePickerLabel} value={preference} onChange={(event) => setPreference(event.target.value as CoManagementLanguagePreference)}>
      {coManagementLanguageOptions.map((option) => <option key={option.value} value={option.value}>{option.value === "system" ? messages.languageSystem : option.nativeName}</option>)}
    </select>
  </label>;
}
