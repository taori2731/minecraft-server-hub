export function serverLabText(locale: AppLocale, key: ServerLabLocaleKey, values: Record<string, string | number> = {}) {
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), catalogs[locale][key]);
}

export function getServerLabLocaleCatalog(locale: AppLocale) {
  return catalogs[locale];
}
